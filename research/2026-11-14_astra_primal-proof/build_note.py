"""Append reproducible exact examples, then translate the same Markdown to TeX.

This deliberately small converter handles the constructs used in this note only.
It preserves every mathematical expression verbatim.
"""
from pathlib import Path
import json,re,sys
HERE=Path(__file__).resolve().parent
ROOT=HERE.parent.parent
sys.path.insert(0,str(HERE))
from check_primal import Primal,edge
import networkx as nx

def numbers(xs): return ','.join(map(str,xs))
def eset(xs,ids): return ','.join('e_{'+str(ids[tuple(x)])+'}' for x in xs)

def examples():
    out=['## 11. Two exact worked examples','',
         'COMPUTED. All data below are regenerated by check_primal.py and build_note.py. Vertices are integers. Face labels are the listed boundary cycles in the rotation system returned by NetworkX. Edge labels are local to each example. The checker imports only graph generators and the facial-walk routine from workings/barnette_lab; it constructs all states, cuts, flows, signs, polynomials and recovered matchings itself. Both colourings put the specified root in the black class.','']
    for name in ['cube','cancellation']:
        d=json.loads((HERE/rf'outputs/{name}.json').read_text())
        g=nx.Graph();g.add_edges_from(d['edges'])
        p=Primal.__new__(Primal)
        p.faces=d['faces']; p.A=d['A']; p.inc={int(b):fs for b,fs in d['incidences'].items()}
        sides={}
        for f,vs in enumerate(d['faces']):
            for u,v in zip(vs,vs[1:]+vs[:1]): sides[u,v]=f
        p.transition={}
        for u,v in d['edges']:
            f,h=sides[u,v],sides[v,u]
            p.transition[f,h]=(edge(u,v),1)
            p.transition[h,f]=(edge(u,v),-1)
        ids={tuple(e):i for i,e in enumerate(d['edges'])}
        out += ['### '+('The cube' if name=='cube' else 'A 20-vertex cancellation example'),'',
                rf'The graph has {len(g)} vertices. Its root is $b_0={d["root"]}$ and its prescribed edge is $e_0^{{\rm prescribed}}={tuple(d["recovery"]["e0"])}$. In the edge numbering below this is ${eset([d["recovery"]["e0"]],ids)}$. The superscript keeps the prescribed edge distinct from the enumerated label $e_0$.','',
                rf'$B=\{{{numbers(d["black"])}\}}$, $W=\{{{numbers(d["white"])}\}}$, $A=\{{{numbers(d["A"])}\}}$, $R=\{{{numbers(d["R"])}\}}$, and $X=\{{{numbers(d["X"])}\}}$.','',
                'The full edge list and flow follow. Every flow value is signed in the black-to-white direction, regardless of the numerical order of its endpoints.','']
        for row in d['flow']:
            i=ids[tuple(row['edge'])]
            out += [rf'$e_{{{i}}}={tuple(row["edge"])}$, $\alpha(e_{{{i}}})={row["value"]}$.','']
        out += ['The facial boundary cycles are:','']
        for i,f in enumerate(d['faces']): out += [rf'$f_{{{i}}}=({numbers(f)})$.','']
        out += ['The black-vertex incidence lists and local potentials are:','']
        for b in d['black']:
            fs=d['incidences'][str(b)]
            if b==d['root']:out += [rf'$b={b}$ has incident faces $({numbers(fs)})$; no state potential at the root is needed.','']
            else:
                vals={v['f']:v['a'] for v in d['weights'] if v['b']==b}
                out += [rf'$b={b}$ has incident faces $({numbers(fs)})$ and potentials $({numbers(vals[f] for f in fs)})$ in that order.','']
        out += ['Every state is listed below as the tuple of assigned face indices in the displayed order of $A$. Its $Q$ list uses the enumerated edges, and $c_s$ is the sum of signs over its partners.','']
        stateids={tuple(s):i for i,s in enumerate(d['states'])}
        for i,row in enumerate(d['coefficients']):
            s=tuple(row['s']);q=[v['edge'] for _,_,v in p.links(s).edges(data=True)]
            out += [rf'$s_{{{i}}}=({numbers(s)})$, $Q_{{s_{i}}}=\{{{eset(sorted(q),ids)}\}}$, $c_{{s_{i}}}={row["coefficient"]}$.','']
        out += [r'Every ordered pair follows, including all of its directed face circuits, cut sides, four-count data and slopes. A tuple of faces gives the cyclic order. Its crossed edges are listed in the same order. In the count tuple the entries are $|S|,|B\cap S|,|E_S|,|U_S|,h,\ell$.','']
        for row in d['pairs']:
            ri=stateids[tuple(row['r'])];si=stateids[tuple(row['s'])]
            out += [rf'Pair $(s_{{{ri}}},s_{{{si}}})$ has sign ${row["sign"]}$.','']
            for c in row['disks']:
                vals=[c[k] for k in ['vertices','black','incident_edges','incident_faces','h','ell']]
                out += [rf'Faces $({numbers(c["faces"])})$; edges $({eset(c["edges"],ids)})$; cut side $S=\{{{numbers(c["shore"])}\}}$. Counts $({numbers(vals)})$; delta-sum ${c["delta"]}$; slope ${c["slope"]}$.','']
        terms=[]
        for i,c in enumerate(d['polynomial']):
            if c: terms.append(('+' if c>0 and terms else '')+str(c)+(rf'z^{i}' if i>1 else 'z' if i else ''))
        out += ['The exact polynomial is','', '$$','Z(z)='+''.join(terms)+'.','$$','']
        if name=='cancellation':
            s=next(tuple(c['s']) for c in d['coefficients'] if c['coefficient']==0)
            mates=[row for row in d['pairs'] if tuple(row['s'])==s]
            q=p.links(s);c=nx.cycle_basis(q)[0]
            out += [rf'The cancelling second state is $s_{{{stateids[s]}}}$. Its two partners are '+
                    ' and '.join(rf'$s_{{{stateids[tuple(row["r"])]}}}$ with sign ${row["sign"]}$' for row in mates)+
                    rf'. The fixed circuit of $Q_s$ is the face sequence $({numbers(c)})$. Reversing its tails interchanges exactly these partners. Their entire state-weight polynomials cancel, not merely their constant terms.','']
            es=[q[f][h]['edge'] for f,h in zip(c,c[1:]+c[:1])]
            cutgraph=g.copy();cutgraph.remove_edges_from(es)
            shore=next(S for S in nx.connected_components(cutgraph) if d['root'] not in S)
            ell=sum(next(v for v in e if v in d['black']) in shore for e in es)
            U={f for f,vs in enumerate(d['faces']) if set(vs)&shore}
            counts=[len(shore),len(shore&set(d['black'])),sum(bool(set(e)&shore) for e in d['edges']),len(U),len(es),ell]
            out += [rf'This cancellation circuit crosses $({eset(es,ids)})$ and has cut side $S=\{{{numbers(sorted(shore))}\}}$. Its four-count tuple is $({numbers(counts)})$, so its odd length is visible directly in G.','']
        rec=d['recovery']; chosen=next(tuple(c['s']) for c in d['coefficients'] if c['coefficient'])
        out += [rf'For recovery choose $s_{{{stateids[chosen]}}}$. The removed edge set is $\{{{eset(rec["removed"],ids)}\}}$.','',
                rf'The recovery tree has edges $\{{{eset(rec["tree"],ids)}\}}$.','',
                rf'The selected perfect matching is $P=\{{{eset(rec["P"],ids)}\}}$.','',
                rf'Its complementary Hamiltonian cycle, in cyclic vertex order, is $({numbers(rec["cycle"])})$. It avoids the prescribed edge.','']
    return '\n'.join(out)

def escape(s):
    return ''.join({'&':r'\&','%':r'\%','#':r'\#','_':r'\_','{':r'\{','}':r'\}','~':r'\textasciitilde{}','^':r'\textasciicircum{}','\\':r'\textbackslash{}'}.get(c,c) for c in s)

def inline(s):
    chunks=re.split(r'(\$[^$]+\$|`[^`]+`|\*\*[^*]+\*\*|\*[^*]+\*)',s)
    out=[]
    for t in chunks:
        if t.startswith('$'):out.append(t.replace(',',r',\allowbreak '))
        elif t.startswith('`'):out.append(r'\nolinkurl{'+t[1:-1]+'}')
        elif t.startswith('**'):out.append(r'\textbf{'+escape(t[2:-2])+'}')
        elif t.startswith('*'):out.append(r'\emph{'+escape(t[1:-1])+'}')
        else:out.append(escape(t))
    return ''.join(out)

def main():
    path=ROOT/'proofs/primal/PRIMAL-PROOF.md'
    main=path.read_text(encoding='utf-8').split('## 11. Two exact worked examples')[0].rstrip()
    main=main.replace('\\\n','\\\\\n') # four aligned rows, idempotence below
    main=main.replace('\\\\\\\n','\\\\\n')
    md=main+'\n\n'+examples()+'\n'
    path.write_text(md,encoding='utf-8')
    (ROOT/'proofs/primal/EXAMPLES.md').write_text(examples(),encoding='utf-8')
    lines=md.splitlines();out=[];math=False
    for line in lines:
        if line=='$$':
            out.append(r'\end{equation*}' if math else r'\begin{equation*}')
            math=not math;continue
        if math:out.append(line);continue
        if line.startswith('# '):continue
        if line.startswith('## '):out.append(r'\section*{'+escape(line[3:])+'}');continue
        if line.startswith('### '):out.append(r'\subsection*{'+escape(line[4:])+'}');continue
        out.append(inline(line))
    pre=r'''\documentclass[a4paper,11pt]{amsart}
\usepackage[margin=1in]{geometry}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{amsmath,amssymb}
\usepackage{microtype}
\usepackage{url}
\usepackage[hidelinks]{hyperref}
\setlength{\emergencystretch}{3em}
\allowdisplaybreaks
\title{Barnette's conjecture in the cubic graph}
\author{Primal reconstruction, gpt-6-astra}
\date{14 November 2026}
\begin{document}
\maketitle
'''
    (ROOT/'proofs/primal/primal.tex').write_text(pre+'\n'.join(out)+'\n\\end{document}\n',encoding='utf-8')

if __name__=='__main__':main()

